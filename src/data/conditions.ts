export const conditionBySlug = (slug: string) => CONDITIONS.find((c) => c.slug === slug)

export const conditionsInGroup = (gid: string) => CONDITIONS.filter((c) => c.group === gid)

export function searchConditions(q: string): Condition[] {
  const s = q.trim().toLowerCase()
  if (s.length < 2) return []
  const score = (c: Condition) => {
    const title = c.title.toLowerCase()
    if (title.startsWith(s)) return 100
    if (title.includes(s)) return 80
    for (const syn of c.synonyms) {
      const y = syn.toLowerCase()
      if (y === s) return 70
      if (y.startsWith(s)) return 60
      if (y.includes(s)) return 40
    }
    if (c.summary.toLowerCase().includes(s)) return 15
    return 0
  }
  return CONDITIONS.map((c) => ({ c, v: score(c) }))
    .filter((x) => x.v > 0)
    .sort((a, b) => b.v - a.v)
    .map((x) => x.c)
}
